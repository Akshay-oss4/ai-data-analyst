"""Reusable Streamlit pieces: KPI cards, finding lists, AI insight display."""
from __future__ import annotations

import streamlit as st
from html import escape
from src.ai.insights import InsightsResult
from src.analysis.findings import Finding
from src.analysis.kpis import KPI
from src.analysis.trends import TrendResult
from src.ui.presenters import PRIORITY_ICONS, SEVERITY_ICONS, kpi_delta


def kpi_cards(kpis: list[KPI], trends: list[TrendResult], per_row: int = 4) -> None:
    for start in range(0, len(kpis), per_row):
        columns = st.columns(per_row)
        for widget, kpi in zip(columns, kpis[start:start + per_row]):
            delta, color, extra = kpi_delta(kpi, trends)
            help_text = f"{kpi.description} {extra}".strip()
            widget.metric(kpi.name, kpi.display, delta=delta, delta_color=color, help=help_text)


_SEVERITY_BORDER = {"high": "#dc2626", "medium": "#ea580c", "low": "#ca8a04", "info": "#4f46e5"}


def finding_list(findings: list[Finding], limit: int | None = None) -> None:
    """Findings as cards with a colored edge. F-numbers match the ones the AI uses (F1 to F12)."""
    shown = findings if limit is None else findings[:limit]
    for number, finding in enumerate(shown, start=1):
        tag = f"F{number} · " if number <= 12 else ""
        color = _SEVERITY_BORDER.get(finding.severity, "#64748b")
        st.markdown(
            f'<div class="finding" style="border-left-color:{color}">'
            f'<div><span class="finding-tag">{escape(tag)}{escape(finding.severity.upper())}</span>'
            f"<strong>{escape(finding.title)}</strong></div>"
            f'<div class="finding-detail">{escape(finding.detail)}</div></div>',
            unsafe_allow_html=True,
        )


def render_insights(result: InsightsResult) -> None:
    if result.source == "llm":
        st.success(f"Written by {result.model}")
    else:
        st.warning(f"Generated by built-in rules instead of an AI model. {result.note}")

    st.markdown("#### Summary")
    st.info(result.summary)

    st.markdown("#### Insights")
    for item in result.insights:
        basis = f"  \n*Based on: {', '.join(item.based_on)}*" if item.based_on else ""
        st.markdown(f"**{item.title}**  \n{item.explanation}{basis}")

    st.markdown("#### Recommendations")
    for rec in result.recommendations:
        basis = f"  \n*Based on: {', '.join(rec.based_on)}*" if rec.based_on else ""
        st.markdown(f"{PRIORITY_ICONS[rec.priority]} **{rec.action}** ({rec.priority} priority)  \n{rec.reason}{basis}")

    if result.caveats:
        st.caption("Caveats: " + " ".join(result.caveats))
    if result.unsupported_numbers:
        st.warning(
            "Please double-check these numbers. They were not found in the computed facts: "
            + ", ".join(result.unsupported_numbers)
        )
    with st.expander("The facts the AI was given (nothing else)"):
        st.code(result.fact_sheet)