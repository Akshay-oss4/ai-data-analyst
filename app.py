NUMERIC_FILL_LABELS = {
    "median": "Fill with median",
    "mean": "Fill with mean",
    "zero": "Fill with 0",
    "none": "Leave missing",
}
CATEGORICAL_FILL_LABELS = {
    "unknown": "Fill with 'Unknown'",
    "mode": "Fill with most common value",
    "none": "Leave missing",
}
SEVERITY_ICONS = {"high": "🔴", "medium": "🟠", "low": "🟡", "info": "🔵"}
PRIORITY_ICONS = {"high": "🔴", "medium": "🟠", "low": "🟢"}


@st.cache_data(show_spinner=False)
def cached_load(data: bytes, filename: str, sheet_name: str | None) -> LoadResult:
    return load_file(data, filename, sheet_name)


@st.cache_data(show_spinner=False)
def cached_clean(df, options: CleaningOptions) -> CleaningResult:
    return clean_dataframe(df, options)


@st.cache_data(show_spinner="Analyzing your data...")
def cached_bundle(cleaning: CleaningResult) -> AnalysisBundle:
    return run_analysis(cleaning)


def render_insights(r: InsightsResult) -> None:
    if r.source == "llm":
        st.success(f"Written by {r.model}")
    else:
        st.warning(f"Generated by built-in rules instead of an AI model. {r.note}")

    st.markdown("#### Summary")
    st.info(r.summary)

    st.markdown("#### Insights")
    for item in r.insights:
        basis = f"  \n*Based on: {', '.join(item.based_on)}*" if item.based_on else ""
        st.markdown(f"**{item.title}**  \n{item.explanation}{basis}")

    st.markdown("#### Recommendations")
    for rec in r.recommendations:
        basis = f"  \n*Based on: {', '.join(rec.based_on)}*" if rec.based_on else ""
        st.markdown(f"{PRIORITY_ICONS[rec.priority]} **{rec.action}** ({rec.priority} priority)  \n{rec.reason}{basis}")

    if r.caveats:
        st.caption("Caveats: " + " ".join(r.caveats))
    if r.unsupported_numbers:
        st.warning(
            "Please double-check these numbers. They were not found in the computed facts: "
            + ", ".join(r.unsupported_numbers)
        )
    with st.expander("The facts the AI was given (nothing else)"):
        st.code(r.fact_sheet)


